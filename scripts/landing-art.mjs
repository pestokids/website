/**
 * Builds the felt night-scene art for the landing page (/).
 *
 *   node scripts/landing-art.mjs
 *
 * Reads the five source layers of each art set from internal/ (private, not in
 * the repo) and writes:
 *   public/landing/{wide,tall}/{layer}-{width}.{hash}.{avif,webp}
 *   app/(marketing)/_components/landing/scene-art.ts (sizes, file URLs, inline placeholders)
 *
 * The hash is the file's content, so next.config.ts can serve public/landing/
 * as immutable: changed art gets a new URL.
 *
 * Commit both. Re-run only when the art changes.
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "internal/landing/gpt/complete/layers");
const OUT = path.join(ROOT, "public/landing");
const MODULE = path.join(ROOT, "app/(marketing)/_components/landing/scene-art.ts");

/** Bottom to top. `file` is the source PNG name inside each set's folder. */
const LAYERS = [
  { name: "sky", file: "01-sky.png" },
  { name: "stars", file: "02-stars-moon.png" },
  { name: "back", file: "03-back-meadow.png" },
  { name: "pesto", file: "04-pesto.png" },
  { name: "front", file: "05-front-flowers.png" },
];

/**
 * wide: 2400×1600, for screens wider than 17:20.
 * tall: 1200×2000, for 17:20 and narrower; about 1080, 1600 and 2000 tall. 1200
 *       is the source width, for 3× phones.
 */
const SETS = [
  { name: "wide", folder: "landscape", width: 2400, height: 1600, widths: [1080, 1920, 2400] },
  { name: "tall", folder: "portrait", width: 1200, height: 2000, widths: [648, 960, 1200] },
];

/** Placeholder width in pixels: tiny, then blurred by the browser. */
const PLACEHOLDER_WIDTH = { wide: 24, tall: 15 };

const kb = (bytes) => `${(bytes / 1024).toFixed(0)} KB`;

/** Renames `{base}.{ext}` to `{base}.{hash}.{ext}` and returns its public URL. */
async function hashName(base, ext) {
  const hash = createHash("sha256").update(await readFile(`${base}.${ext}`)).digest("hex").slice(0, 10);
  await rename(`${base}.${ext}`, `${base}.${hash}.${ext}`);
  return `/${path.relative(path.join(ROOT, "public"), `${base}.${hash}.${ext}`)}`;
}

/** Builds every layer at every width; returns the URLs by `{layer}-{width}.{ext}`. */
async function buildSet(set) {
  const dir = path.join(OUT, set.name);
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });

  const files = {};
  for (const layer of LAYERS) {
    const source = path.join(SOURCE, set.folder, layer.file);
    const meta = await sharp(source).metadata();
    if (meta.width !== set.width || meta.height !== set.height) {
      throw new Error(`${source} is ${meta.width}×${meta.height}, expected ${set.width}×${set.height}`);
    }
    for (const width of set.widths) {
      const resized = sharp(source).resize({ width, kernel: "lanczos3" });
      const base = path.join(dir, `${layer.name}-${width}`);
      await resized.clone().avif({ quality: 52, effort: 7, chromaSubsampling: "4:4:4" }).toFile(`${base}.avif`);
      await resized.clone().webp({ quality: 78, alphaQuality: 90, effort: 6 }).toFile(`${base}.webp`);
      const [avif, webp] = await Promise.all([stat(`${base}.avif`), stat(`${base}.webp`)]);
      console.log(`${set.name}/${layer.name}-${width}: avif ${kb(avif.size)}, webp ${kb(webp.size)}`);
      for (const ext of ["avif", "webp"]) files[`${layer.name}-${width}.${ext}`] = await hashName(base, ext);
    }
  }
  return files;
}

/** All five layers flattened into one tiny WebP, as a data URL. */
async function placeholder(set) {
  const layers = LAYERS.map((layer) => ({ input: path.join(SOURCE, set.folder, layer.file) }));
  const flat = await sharp(layers[0].input).composite(layers.slice(1)).png().toBuffer();
  const tiny = await sharp(flat)
    .resize({ width: PLACEHOLDER_WIDTH[set.name] })
    .webp({ quality: 50, smartSubsample: true })
    .toBuffer();
  return `data:image/webp;base64,${tiny.toString("base64")}`;
}

async function writeModule(placeholders, files) {
  const sets = SETS.map(
    (set) => `  ${set.name}: {
    width: ${set.width},
    height: ${set.height},
    widths: [${set.widths.join(", ")}],
    placeholder:
      "${placeholders[set.name]}",
    files: {
${Object.entries(files[set.name])
  .map(([name, url]) => `      "${name}": "${url}",`)
  .join("\n")}
    },
  },`,
  ).join("\n");
  const source = `// Generated by scripts/landing-art.mjs. Don't edit by hand; re-run the script.

/**
 * Source size, generated widths, an inline blurred placeholder and the
 * content-hashed file URLs (by \`{layer}-{width}.{format}\`) for each art set.
 */
export const sceneArt = {
${sets}
} as const;

export const sceneLayers = [${LAYERS.map((l) => `"${l.name}"`).join(", ")}] as const;
`;
  await writeFile(MODULE, source);
}

const placeholders = {};
const files = {};
for (const set of SETS) {
  files[set.name] = await buildSet(set);
  placeholders[set.name] = await placeholder(set);
  console.log(`${set.name} placeholder: ${placeholders[set.name].length} bytes`);
}
await writeModule(placeholders, files);
